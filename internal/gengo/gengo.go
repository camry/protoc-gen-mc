package gengo

import (
    "fmt"
    "strings"

    "github.com/samber/lo"
    "google.golang.org/protobuf/compiler/protogen"
    "google.golang.org/protobuf/reflect/protoreflect"

    "protoc-gen-mc/internal/version"
)

const (
    ReceiverVar = "x"
)

// GenerateFile 生成 .pb.mc.go 文件的内容。
func GenerateFile(gen *protogen.Plugin, file *protogen.File) {
    filename := file.GeneratedFilenamePrefix + ".pb.mc.go"
    g := gen.NewGeneratedFile(filename, file.GoImportPath)

    g.P("// Code generated by protoc-gen-mc. DO NOT EDIT.")
    g.P("// versions:")
    protocGenMcVersion := version.String()
    protocVersion := "(unknown)"
    if v := gen.Request.GetCompilerVersion(); v != nil {
        protocVersion = fmt.Sprintf("v%v.%v.%v", v.GetMajor(), v.GetMinor(), v.GetPatch())
        if s := v.GetSuffix(); s != "" {
            protocVersion += "-" + s
        }
    }
    g.P("// \tprotoc-gen-mc ", protocGenMcVersion)
    g.P("// \tprotoc        ", protocVersion)
    if file.Proto.GetOptions().GetDeprecated() {
        g.P("// ", file.Desc.Path(), " is a deprecated file.")
    } else {
        g.P("// source: ", file.Desc.Path())
    }
    g.P()

    g.P("package ", file.GoPackageName)
    g.P()

    g.P("import (")
    g.P("\t\"gitea.meigushi.go/meigushi/mc\"")
    g.P("\t\"go.mongodb.org/mongo-driver/v2/bson\"")
    g.P(")")
    g.P()

    // 生成所有枚举类型的代码
    for _, enum := range file.Enums {
        generateEnum(g, enum)
    }

    // 生成所有消息类型的代码（包括嵌套消息）
    for _, message := range file.Messages {
        generateMessageStructRecursive(g, message)
    }
}

// generateEnum 生成枚举类型的代码
func generateEnum(g *protogen.GeneratedFile, enum *protogen.Enum) {
    enumName := enum.Desc.Name()

    // 生成枚举类型定义
    g.P("type ", enumName, " int32")
    g.P()

    // 生成枚举值常量
    g.P("const (")
    for _, value := range enum.Values {
        g.P(enumName, "_", value.Desc.Name(), " ", enumName, " = ", value.Desc.Number())
    }
    g.P(")")
    g.P()
}

// generateMessageStructRecursive 递归生成消息结构体及其相关方法
func generateMessageStructRecursive(g *protogen.GeneratedFile, message *protogen.Message) {
    if message.Desc.IsMapEntry() {
        return
    }
    // 生成当前消息结构体
    generateMessageStruct(g, message)
    // 递归生成嵌套消息结构体
    for _, nestedMessage := range message.Messages {
        generateMessageStructRecursive(g, nestedMessage)
    }
}

// generateMessageStruct 生成消息结构体及其相关方法
func generateMessageStruct(g *protogen.GeneratedFile, message *protogen.Message) {
    messageName := getFullMessageName(message)

    // 确定是否是顶级消息（包含 key 字段的消息）
    isTopLevel := isTopLevelMessage(message)
    var baseStruct string
    if isTopLevel {
        keyField := findKeyField(message)
        if keyField != nil {
            keyType := getGoType(keyField.Desc) // 获取 _id 字段的实际类型
            baseStruct = fmt.Sprintf("mc.MessageTop[*%s, %s]", messageName, keyType)
        } else {
            baseStruct = "mc.MessageTop[*" + messageName + ", int64]" // 默认使用 int64
        }
    } else {
        baseStruct = "mc.MessageSub"
    }

    // 生成结构体定义
    g.P("type ", messageName, " struct {")
    g.P("\t", baseStruct)
    g.P()

    for _, field := range message.Fields {
        fieldName := getPrivateFieldName(field)
        fieldType := getFieldType(field)
        // 添加 proto 定义的注释
        trailingComments := field.Comments.Trailing
        if trailingComments != "" {
            g.P("\t", fieldName, " ", fieldType, " ", trailingComment(trailingComments))
        } else {
            g.P("\t", fieldName, " ", fieldType)
        }
    }
    g.P("}")
    g.P()

    // 生成解码注册变量
    generateDecoderRegistration(g, message)

    // 生成构造函数（仅对顶级消息）
    if isTopLevel {
        generateTopLevelConstructor(g, message)
        g.P()

        // 生成 Table 方法
        generateTableMethod(g, message)
        g.P()
    } else {
        generateSubConstructor(g, message)
        g.P()
    }

    // 生成 Marshal 方法
    generateMarshalMethod(g, message)
    g.P()
    // 生成 Unmarshal 方法
    generateUnmarshalMethod(g, message)
    g.P()

    // 生成所有字段的 Get 和 Set 方法
    for _, field := range message.Fields {
        generateFieldMethods(g, message, field)
    }
}

// isTopLevelMessage 判断是否是顶级消息（包含 key 字段的消息）
func isTopLevelMessage(message *protogen.Message) bool {
    for _, field := range message.Fields {
        if field.Desc.Name() == "_id" {
            return true
        }
    }
    return false
}

// findKeyField 查找作为 key 的字段
func findKeyField(message *protogen.Message) *protogen.Field {
    for _, field := range message.Fields {
        if field.Desc.Name() == "_id" {
            return field
        }
    }
    return nil
}

// getPrivateFieldName 获取私有字段名（首字母小写）
func getPrivateFieldName(field *protogen.Field) string {
    name := string(field.Desc.Name())
    // 特殊处理 _id 字段，保留原样
    if name == "_id" {
        return "_id"
    }
    return lo.CamelCase(name)
}

// getPublicFieldName 获取公共字段名（首字母大写）
func getPublicFieldName(field *protogen.Field) string {
    name := string(field.Desc.Name())
    // 特殊处理 _id 字段，将其转换为 Id
    if name == "_id" {
        return "XId"
    }
    return lo.PascalCase(name)
}

// getPrivateFieldNameFromPublic 从公共字段名获取私有字段名
func getPrivateFieldNameFromPublic(publicFieldName string) string {
    if len(publicFieldName) > 0 {
        return strings.ToLower(string(publicFieldName[0])) + publicFieldName[1:]
    }
    return publicFieldName
}

// getDecoderVariableName 获取解码器变量名，保持嵌套消息名称的下划线格式
func getDecoderVariableName(messageName string) string {
    // 将名称转换为小写开头的格式，保留下划线
    // 如 A_B_C_D -> a_B_C_D
    if len(messageName) > 0 {
        return strings.ToLower(string(messageName[0])) + messageName[1:] + "Decode"
    }
    return messageName
}

// isNumericField 检查字段是否为数值类型
func isNumericField(field *protogen.Field) bool {
    switch field.Desc.Kind() {
    case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind,
        protoreflect.Uint32Kind, protoreflect.Fixed32Kind,
        protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind,
        protoreflect.Uint64Kind, protoreflect.Fixed64Kind,
        protoreflect.FloatKind, protoreflect.DoubleKind:
        return true
    default:
        return false
    }
}

// getFullMessageName 获取消息的完整名称，包括嵌套结构
func getFullMessageName(message *protogen.Message) string {
    fullName := string(message.Desc.FullName())
    packageName := string(message.Desc.ParentFile().Package())
    return getFullMessageNameFilterPackage(fullName, packageName)
}

// getFullMessageNameByFieldDescriptor 获取字段的消息的完整名称，包括嵌套结构
func getFullMessageNameByFieldDescriptor(desc protoreflect.FieldDescriptor) string {
    fullName := string(desc.Message().FullName())
    packageName := string(desc.ParentFile().Package())
    return getFullMessageNameFilterPackage(fullName, packageName)
}

// getFullMessageNameFilterPackage 获取消息的完整名称，过滤掉包名
func getFullMessageNameFilterPackage(fullName string, packageName string) string {
    var msgName string
    // 如果消息在同一个包内，移除包名前缀
    if packageName != "" && strings.HasPrefix(fullName, packageName+".") {
        // 移除包名前缀，保留嵌套结构
        msgName = strings.Replace(fullName, packageName+".", "", 1)
    } else {
        // 使用完整名称
        msgName = fullName
    }
    // 将嵌套分隔符替换为下划线
    return strings.Replace(msgName, ".", "_", -1)
}

// getEnumTypeName 获取枚举字段的类型名称
func getEnumTypeName(field *protogen.Field) string {
    enumDesc := field.Desc.Enum()
    fullName := string(enumDesc.FullName())
    packageName := string(field.Desc.ParentFile().Package())
    return getEnumTypeNameFilterPackage(fullName, packageName)
}

// getEnumTypeNameByDesc 通过字段描述符获取枚举类型名称
func getEnumTypeNameByDesc(desc protoreflect.FieldDescriptor) string {
    enumDesc := desc.Enum()
    fullName := string(enumDesc.FullName())
    packageName := string(desc.ParentFile().Package())
    return getEnumTypeNameFilterPackage(fullName, packageName)
}

// getEnumTypeNameFilterPackage 获取枚举类型名称，过滤掉包名
func getEnumTypeNameFilterPackage(fullName string, packageName string) string {
    if packageName != "" && strings.HasPrefix(fullName, packageName+".") {
        return strings.Replace(fullName, packageName+".", "", 1)
    }
    return fullName
}

// getFieldType 获取字段的 Go 类型
func getFieldType(field *protogen.Field) string {
    switch field.Desc.Kind() {
    case protoreflect.EnumKind:
        // 处理枚举类型
        if field.Desc.IsList() {
            // repeated 枚举类型
            enumName := getEnumTypeName(field)
            return fmt.Sprintf("*mc.ListBase[%s]", enumName)
        }
        return getEnumTypeName(field)
    case protoreflect.MessageKind:
        if field.Desc.IsMap() {
            // 处理 map 类型
            mapK := field.Message.Fields[0]
            mapV := field.Message.Fields[1]
            keyType := getGoType(mapK.Desc)
            valueType := getGoType(mapV.Desc)
            if mapV.Desc.Kind() == protoreflect.MessageKind {
                // 如果 map 的值是消息类型，则使用指针
                nestedMessageName := getFullMessageName(mapV.Message)
                return fmt.Sprintf("*mc.MapMessage[%s, *%s]", keyType, nestedMessageName)
            }
            return fmt.Sprintf("*mc.MapBase[%s, %s]", keyType, valueType)
        } else if field.Desc.IsList() {
            // 处理 repeated 类型
            if field.Desc.Kind() == protoreflect.MessageKind {
                // 如果 repeated 的元素是消息类型，使用 ListMessage
                nestedMessageName := getFullMessageName(field.Message)
                return fmt.Sprintf("*mc.ListMessage[*%s]", nestedMessageName)
            }
            // 如果 repeated 的元素是基本类型，使用 ListBase
            elementType := getGoType(field.Desc)
            return fmt.Sprintf("*mc.ListBase[%s]", elementType)
        }
        // 普通消息类型
        nestedMessageName := getFullMessageName(field.Message)
        return "*" + nestedMessageName
    case protoreflect.StringKind:
        if field.Desc.IsList() {
            return "*mc.ListBase[string]"
        }
        return "string"
    case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
        if field.Desc.IsList() {
            return "*mc.ListBase[int32]"
        }
        return "int32"
    case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
        if field.Desc.IsList() {
            return "*mc.ListBase[uint32]"
        }
        return "uint32"
    case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
        if field.Desc.IsList() {
            return "*mc.ListBase[int64]"
        }
        return "int64"
    case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
        if field.Desc.IsList() {
            return "*mc.ListBase[uint64]"
        }
        return "uint64"
    case protoreflect.BoolKind:
        if field.Desc.IsList() {
            return "*mc.ListBase[bool]"
        }
        return "bool"
    case protoreflect.FloatKind:
        if field.Desc.IsList() {
            return "*mc.ListBase[float32]"
        }
        return "float32"
    case protoreflect.DoubleKind:
        if field.Desc.IsList() {
            return "*mc.ListBase[float64]"
        }
        return "float64"
    default:
        return getGoType(field.Desc)
    }
}

// getGoType 获取基本 Go 类型
func getGoType(desc protoreflect.FieldDescriptor) string {
    switch desc.Kind() {
    case protoreflect.BoolKind:
        return "bool"
    case protoreflect.EnumKind:
        return getEnumTypeNameByDesc(desc)
    case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
        return "int32"
    case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
        return "uint32"
    case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
        return "int64"
    case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
        return "uint64"
    case protoreflect.FloatKind:
        return "float32"
    case protoreflect.DoubleKind:
        return "float64"
    case protoreflect.StringKind:
        return "string"
    case protoreflect.BytesKind:
        return "[]byte"
    case protoreflect.MessageKind, protoreflect.GroupKind:
        return "*" + getFullMessageNameByFieldDescriptor(desc)
    default:
        return "any"
    }
}

// generateDecoderRegistration 生成解码注册代码
func generateDecoderRegistration(g *protogen.GeneratedFile, message *protogen.Message) {
    messageName := getFullMessageName(message)

    // 对于嵌套消息名称，我们直接在名称后添加 Decode，而不使用 CamelCase
    decoderVarName := getDecoderVariableName(messageName)
    g.P("var ", decoderVarName, " = mc.Register(&", messageName, "{},")

    for _, field := range message.Fields {
        privateFieldName := getPrivateFieldName(field)
        fieldType := field.Desc.Kind()

        g.P("\tmc.NewDecodePair(\"", privateFieldName, "\", mc.NewDecodeField(func(vr bson.ValueReader, v *", messageName, ") (err error) {")

        switch fieldType {
        case protoreflect.MessageKind:
            if field.Desc.IsMap() {
                // Map 类型
                mapParams := field.Message.Fields
                valueIsMessage := mapParams[1].Desc.Kind() == protoreflect.MessageKind

                if valueIsMessage {
                    nestedMessageName := getFullMessageName(mapParams[1].Message)
                    g.P("\t\tv.", privateFieldName, " = mc.NewMapMessage[", getGoType(mapParams[0].Desc), ", *", nestedMessageName, "](v, \"", privateFieldName, "\", new", nestedMessageName, ")")
                    g.P("\t\terr = v.", privateFieldName, ".Decode(vr, v.", privateFieldName, ")")
                } else {
                    g.P("\t\tv.", privateFieldName, " = mc.NewMapBase[", getGoType(mapParams[0].Desc), ", ", getGoType(mapParams[1].Desc), "](v, \"", privateFieldName, "\")")
                    g.P("\t\terr = v.", privateFieldName, ".Decode(vr, v.", privateFieldName, ")")
                }
            } else if field.Desc.IsList() {
                // Repeated 类型
                if field.Desc.Kind() == protoreflect.MessageKind {
                    // 如果 repeated 的元素是消息类型，使用 NewListMessage
                    nestedMessageName := getFullMessageName(field.Message)
                    g.P("\t\tv.", privateFieldName, " = mc.NewListMessage[*", nestedMessageName, "](v, \"", privateFieldName, "\", new", nestedMessageName, ")")
                    g.P("\t\terr = v.", privateFieldName, ".Decode(vr, v.", privateFieldName, ")")
                } else {
                    // 如果 repeated 的元素是基本类型，使用 NewListBase
                    elementType := getGoType(field.Desc)
                    g.P("\t\tv.", privateFieldName, " = mc.NewListBase[", elementType, "](v, \"", privateFieldName, "\")")
                    g.P("\t\terr = v.", privateFieldName, ".Decode(vr, v.", privateFieldName, ")")
                }
            } else {
                // 普通消息类型
                nestedMessageName := getFullMessageName(field.Message)
                g.P("\t\tv.", privateFieldName, " = new", nestedMessageName, "(v, \"", privateFieldName, "\")")
                decoderVarName := getDecoderVariableName(nestedMessageName)
                g.P("\t\terr = ", decoderVarName, ".Decode(vr, v.", privateFieldName, ")")
            }
        case protoreflect.StringKind:
            if field.Desc.IsList() {
                g.P("\t\tv.", privateFieldName, " = mc.NewListBase[string](v, \"", privateFieldName, "\")")
                g.P("\t\terr = v.", privateFieldName, ".Decode(vr, v.", privateFieldName, ")")
            } else {
                g.P("\t\tv.", privateFieldName, ", err = mc.StringDecode(vr)")
            }
        case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
            if field.Desc.IsList() {
                g.P("\t\tv.", privateFieldName, " = mc.NewListBase[int32](v, \"", privateFieldName, "\")")
                g.P("\t\terr = v.", privateFieldName, ".Decode(vr, v.", privateFieldName, ")")
            } else {
                g.P("\t\tv.", privateFieldName, ", err = mc.Int32Decode(vr)")
            }
        case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
            if field.Desc.IsList() {
                g.P("\t\tv.", privateFieldName, " = mc.NewListBase[uint32](v, \"", privateFieldName, "\")")
                g.P("\t\terr = v.", privateFieldName, ".Decode(vr, v.", privateFieldName, ")")
            } else {
                g.P("\t\tv.", privateFieldName, ", err = mc.UInt32Decode(vr)")
            }
        case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
            if field.Desc.IsList() {
                g.P("\t\tv.", privateFieldName, " = mc.NewListBase[int64](v, \"", privateFieldName, "\")")
                g.P("\t\terr = v.", privateFieldName, ".Decode(vr, v.", privateFieldName, ")")
            } else {
                g.P("\t\tv.", privateFieldName, ", err = mc.Int64Decode(vr)")
            }
        case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
            if field.Desc.IsList() {
                g.P("\t\tv.", privateFieldName, " = mc.NewListBase[uint64](v, \"", privateFieldName, "\")")
                g.P("\t\terr = v.", privateFieldName, ".Decode(vr, v.", privateFieldName, ")")
            } else {
                g.P("\t\tv.", privateFieldName, ", err = mc.UInt64Decode(vr)")
            }
        case protoreflect.BoolKind:
            if field.Desc.IsList() {
                g.P("\t\tv.", privateFieldName, " = mc.NewListBase[bool](v, \"", privateFieldName, "\")")
                g.P("\t\terr = v.", privateFieldName, ".Decode(vr, v.", privateFieldName, ")")
            } else {
                g.P("\t\tv.", privateFieldName, ", err = mc.BoolDecode(vr)")
            }
        case protoreflect.FloatKind:
            if field.Desc.IsList() {
                g.P("\t\tv.", privateFieldName, " = mc.NewListBase[float32](v, \"", privateFieldName, "\")")
                g.P("\t\terr = v.", privateFieldName, ".Decode(vr, v.", privateFieldName, ")")
            } else {
                g.P("\t\tv.", privateFieldName, ", err = mc.Float32Decode(vr)")
            }
        case protoreflect.DoubleKind:
            if field.Desc.IsList() {
                g.P("\t\tv.", privateFieldName, " = mc.NewListBase[float64](v, \"", privateFieldName, "\")")
                g.P("\t\terr = v.", privateFieldName, ".Decode(vr, v.", privateFieldName, ")")
            } else {
                g.P("\t\tv.", privateFieldName, ", err = mc.Float64Decode(vr)")
            }
        case protoreflect.EnumKind:
            enumTypeName := getEnumTypeName(field)
            if field.Desc.IsList() {
                g.P("\t\tv.", privateFieldName, " = mc.NewListBase[", enumTypeName, "](v, \"", privateFieldName, "\")")
                g.P("\t\terr = v.", privateFieldName, ".Decode(vr, v.", privateFieldName, ")")
            } else {
                g.P("\t\tv.", privateFieldName, ", err = mc.EnumDecode[", enumTypeName, "](vr)")
            }
        case protoreflect.BytesKind:
            g.P("\t\tv.", privateFieldName, ", err = mc.BinaryDecode(vr)")
        default:
            g.P("\t\t// Unsupported type for field ", privateFieldName)
        }

        g.P("\t\treturn")
        g.P("\t})),")
    }

    g.P(")")
    g.P()
}

// generateTopLevelConstructor 生成顶级消息的构造函数
func generateTopLevelConstructor(g *protogen.GeneratedFile, message *protogen.Message) {
    messageName := getFullMessageName(message)

    keyField := findKeyField(message)
    var keyType string
    if keyField != nil {
        keyType = getGoType(keyField.Desc)
    } else {
        keyType = "int64" // 默认类型
    }

    g.P("func New", messageName, "(adapter mc.IAdapter[*", messageName, ", ", keyType, "], k ", keyType, ") *", messageName, " {")
    g.P("\t", ReceiverVar, " := &", messageName, "{}")
    if keyField != nil {
        privateFieldName := getPrivateFieldName(keyField)
        g.P("\t", ReceiverVar, ".", privateFieldName, " = k")
    }
    g.P("\t", ReceiverVar, ".Bind(adapter, ", ReceiverVar, ", k)")
    g.P("\treturn ", ReceiverVar, "")
    g.P("}")
}

// generateSubConstructor 生成子消息的构造函数
func generateSubConstructor(g *protogen.GeneratedFile, message *protogen.Message) {
    messageName := getFullMessageName(message)

    g.P("func new", messageName, "(parent mc.IMessage, key any) *", messageName, " {")
    g.P("\t", ReceiverVar, " := &", messageName, "{}")
    g.P("\t", ReceiverVar, ".Bind(parent, key)")
    g.P("\treturn ", ReceiverVar, "")
    g.P("}")
}

// generateTableMethod 生成 Table 方法
func generateTableMethod(g *protogen.GeneratedFile, message *protogen.Message) {
    messageName := getFullMessageName(message)

    g.P("func (", ReceiverVar, " *", messageName, ") Table() string {")
    g.P("\treturn \"", lo.PascalCase(messageName), "\"") // 动态返回消息类型的名称作为表名
    g.P("}")
}

// generateMarshalMethod 生成 Marshal 方法
func generateMarshalMethod(g *protogen.GeneratedFile, message *protogen.Message) {
    messageName := getFullMessageName(message)

    g.P("func (", ReceiverVar, " *", messageName, ") Marshal() bson.M {")
    g.P("\tm := make(bson.M)")

    for _, field := range message.Fields {
        privateFieldName := getPrivateFieldName(field)
        publicFieldName := getPublicFieldName(field)

        if field.Desc.Name() == "_id" && isTopLevelMessage(message) {
            // 对于顶级消息的 _id 字段，使用 XId 方法获取值
            g.P("\tm[\"", privateFieldName, "\"] = ", ReceiverVar, ".GetXId()")
        } else {
            // 根据字段类型决定如何序列化
            // repeated、map 和 message 类型都需要调用 Marshal 方法
            if (field.Desc.IsList() && field.Desc.Kind() != protoreflect.BytesKind) || field.Desc.IsMap() || field.Desc.Kind() == protoreflect.MessageKind {
                // repeated、map 和 message 类型有 Marshal 方法
                g.P("\tm[\"", privateFieldName, "\"] = ", ReceiverVar, ".Get", publicFieldName, "().Marshal()")
            } else {
                // 基本类型直接获取值
                g.P("\tm[\"", privateFieldName, "\"] = ", ReceiverVar, ".Get", publicFieldName, "()")
            }
        }
    }
    g.P("\treturn m")
    g.P("}")
}

// generateUnmarshalMethod 生成 Unmarshal 方法
func generateUnmarshalMethod(g *protogen.GeneratedFile, message *protogen.Message) {
    messageName := getFullMessageName(message)
    g.P("func (", ReceiverVar, " *", messageName, ") Unmarshal(m bson.M) error {")
    g.P("\tdecode, err := mc.GetDecode(", ReceiverVar, ")")
    g.P("\tif err != nil {")
    g.P("\t\treturn err")
    g.P("\t}")
    g.P("\tvr, err := mc.MToValueReader(m)")
    g.P("\tif err != nil {")
    g.P("\t\treturn err")
    g.P("\t}")
    g.P("\treturn decode.Decode(vr, ", ReceiverVar, ")")
    g.P("}")
}

// generateFieldMethods 生成字段的 Get 和 Set 方法
func generateFieldMethods(g *protogen.GeneratedFile, message *protogen.Message, field *protogen.Field) {
    messageName := getFullMessageName(message)
    publicFieldName := getPublicFieldName(field)
    privateFieldName := getPrivateFieldName(field)

    // 对于 repeated、map 和 message 字段，只生成 Get 方法
    if field.Desc.IsList() || field.Desc.IsMap() || field.Desc.Kind() == protoreflect.MessageKind {
        // 为 repeated、map 和 message 字段只生成 Get 方法
        g.P() // 添加空行
        generateGetMethod(g, messageName, publicFieldName, privateFieldName, field)
    } else {
        // 为其他字段生成 Get 和 Set 方法
        g.P() // 添加空行
        generateGetMethod(g, messageName, publicFieldName, privateFieldName, field)

        // 跳过为 _id 字段生成 Set 方法和数值类型字段的 Incr 和 Decr 方法
        if string(field.Desc.Name()) != "_id" {
            g.P() // 添加空行
            generateSetMethod(g, messageName, publicFieldName, privateFieldName, field)

            // 为数值类型字段生成 Incr 和 Decr 方法
            if isNumericField(field) {
                g.P() // 添加空行
                generateNumericMethods(g, messageName, publicFieldName, privateFieldName, field)
            }
        }
    }

    // 根据字段类型生成特定方法
    // 跳过为 _id 字段生成 Incr 和 Decr 方法
    if string(field.Desc.Name()) != "_id" {
        // 为普通消息类型字段生成 Unset 方法（排除 repeated 和 map 类型）
        if field.Desc.Kind() == protoreflect.MessageKind && !field.Desc.IsList() && !field.Desc.IsMap() {
            g.P() // 添加空行
            generateUnsetMethod(g, messageName, publicFieldName, privateFieldName, field)
        }
    }
}

// generateGetMethod 生成 Get 方法
func generateGetMethod(g *protogen.GeneratedFile, messageName, publicFieldName, privateFieldName string, field *protogen.Field) {
    returnType := getFieldType(field)

    g.P("func (", ReceiverVar, " *", messageName, ") Get", publicFieldName, "() ", returnType, " {")

    // 对于消息类型字段（非 map 和非 repeated），添加 nil 检查
    if field.Desc.Kind() == protoreflect.MessageKind && !field.Desc.IsMap() && !field.Desc.IsList() {
        g.P("\tif ", ReceiverVar, ".", privateFieldName, " == nil {")
        nestedMessageName := getFullMessageName(field.Message)
        g.P("\t\t", ReceiverVar, ".", privateFieldName, " = new", nestedMessageName, "(", ReceiverVar, ", \"", privateFieldName, "\")")
        g.P("\t}")
    } else if field.Desc.Kind() == protoreflect.MessageKind && field.Desc.IsMap() {
        // 对于 Map 类型字段，添加 nil 检查
        g.P("\tif ", ReceiverVar, ".", privateFieldName, " == nil {")
        mapK := field.Message.Fields[0]
        mapV := field.Message.Fields[1]
        if mapV.Desc.Kind() == protoreflect.MessageKind {
            nestedMessageName := getFullMessageName(mapV.Message)
            g.P("\t\t", ReceiverVar, ".", privateFieldName, " = mc.NewMapMessage[", getGoType(mapK.Desc), ", *", nestedMessageName, "](", ReceiverVar, ", \"", privateFieldName, "\", new", nestedMessageName, ")")
        } else {
            g.P("\t\t", ReceiverVar, ".", privateFieldName, " = mc.NewMapBase[", getGoType(mapK.Desc), ", ", getGoType(mapV.Desc), "](", ReceiverVar, ", \"", privateFieldName, "\")")
        }
        g.P("\t}")
    } else if field.Desc.IsList() && field.Desc.Kind() != protoreflect.BytesKind {
        // 对于 Repeated 类型字段，添加 nil 检查
        g.P("\tif ", ReceiverVar, ".", privateFieldName, " == nil {")
        if field.Desc.Kind() == protoreflect.MessageKind {
            // 如果 repeated 的元素是消息类型，使用 NewListMessage
            nestedMessageName := getFullMessageName(field.Message)
            g.P("\t\t", ReceiverVar, ".", privateFieldName, " = mc.NewListMessage[*", nestedMessageName, "](", ReceiverVar, ", \"", privateFieldName, "\", new", nestedMessageName, ")")
        } else {
            // 如果 repeated 的元素是基本类型，使用 NewListBase
            elementType := getGoType(field.Desc)
            g.P("\t\t", ReceiverVar, ".", privateFieldName, " = mc.NewListBase[", elementType, "](", ReceiverVar, ", \"", privateFieldName, "\")")
        }
        g.P("\t}")
    }

    g.P("\treturn ", ReceiverVar, ".", privateFieldName)
    g.P("}")
}

// generateSetMethod 生成 Set 方法
func generateSetMethod(g *protogen.GeneratedFile, messageName, publicFieldName, privateFieldName string, field *protogen.Field) {
    paramType := getFieldType(field)

    g.P("func (", ReceiverVar, " *", messageName, ") Set", publicFieldName, "(value ", paramType, ") {")
    g.P("\t", ReceiverVar, ".", privateFieldName, " = value")
    g.P("\t", ReceiverVar, ".Set(\"", privateFieldName, "\", value)")
    g.P("}")
}

// generateUnsetMethod 生成 Unset 方法
func generateUnsetMethod(g *protogen.GeneratedFile, messageName, publicFieldName, privateFieldName string, field *protogen.Field) {
    g.P("func (", ReceiverVar, " *", messageName, ") Unset", publicFieldName, "() {")
    g.P("\t", ReceiverVar, ".", privateFieldName, " = nil")
    g.P("\t", ReceiverVar, ".Unset(\"", privateFieldName, "\")")
    g.P("}")
}

// generateNumericMethods 生成数值类型的方法
func generateNumericMethods(g *protogen.GeneratedFile, messageName, publicFieldName, privateFieldName string, field *protogen.Field) {
    fieldType := getGoType(field.Desc)

    // 生成 Incr 方法
    g.P("func (", ReceiverVar, " *", messageName, ") Incr", publicFieldName, "(value ", fieldType, ") ", fieldType, " {")
    g.P("\t", ReceiverVar, ".", privateFieldName, " += value")
    g.P("\t", ReceiverVar, ".Set(\"", privateFieldName, "\", ", ReceiverVar, ".", privateFieldName, ")")
    g.P("\treturn ", ReceiverVar, ".", privateFieldName)
    g.P("}")

    g.P()

    // 生成 Decr 方法
    g.P("func (", ReceiverVar, " *", messageName, ") Decr", publicFieldName, "(value ", fieldType, ") ", fieldType, " {")
    g.P("\t", ReceiverVar, ".", privateFieldName, " -= value")
    g.P("\t", ReceiverVar, ".Set(\"", privateFieldName, "\", ", ReceiverVar, ".", privateFieldName, ")")
    g.P("\treturn ", ReceiverVar, ".", privateFieldName)
    g.P("}")
}
